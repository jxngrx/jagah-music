const remoteCache = new Map();

export function lyricAt(cues, time) {
  if (!cues?.length) return null;
  let line = cues[0].line;
  for (const c of cues) {
    if (time >= c.t) line = c.line;
    else break;
  }
  return line;
}

export function lyricIndex(cues, time) {
  if (!cues?.length) return -1;
  let i = 0;
  for (let n = 0; n < cues.length; n++) {
    if (time >= cues[n].t) i = n;
    else break;
  }
  return i;
}

/** Fetch synced lyrics via /api/lyrics (LRCLib). Falls back to pack lyricsById. */
export async function fetchLyrics({ id, title, artist, duration = 0 }) {
  if (id && lyricsById[id]?.length) return lyricsById[id];
  if (id && remoteCache.has(id)) return remoteCache.get(id);

  const params = new URLSearchParams({
    title: (title || '').slice(0, 120),
    artist: (artist || '').slice(0, 120),
  });
  if (duration > 30) params.set('duration', String(Math.round(duration)));

  try {
    const res = await fetch('/api/lyrics?' + params.toString());
    if (!res.ok) {
      if (id) remoteCache.set(id, null);
      return null;
    }
    const data = await res.json();
    const cues = Array.isArray(data?.cues) && data.cues.length ? data.cues : null;
    if (id) remoteCache.set(id, cues);
    if (cues && id) lyricsById[id] = cues;
    return cues;
  } catch {
    if (id) remoteCache.set(id, null);
    return null;
  }
}
